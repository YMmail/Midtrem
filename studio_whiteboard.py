"""studio_whiteboard.py - ไวท์บอร์ดผนังตะวันตก (PyOpenGL ล้วน)  ใช้: whiteboard()  วาดที่ x=0, z 2.3-7.1"""
from OpenGL.GL import *
from studio_gfx import box, gquad, ball, tube, vcylinder

INCH = 0.0254
Z0, Z1 = 2.3, 7.1


def whiteboard():
    z0, z1 = Z0, Z1
    zm = (z0 + z1) / 2
    y0 = 1.05
    y1 = y0 + 47.5 * INCH
    ytop = y1 + 0.10
    brown, dark, kraft = (0.20, 0.11, 0.08), (0.12, 0.07, 0.05), (0.72, 0.56, 0.38)
    box(0.0, y0, z0, 0.03, y1, z1, (0.94, 0.95, 0.96))
    box(0.0, y1, z0 - 0.04, 0.09, y1 + 0.10, z1 + 0.04, brown)
    box(0.0, y0 - 0.06, z0 - 0.04, 0.12, y0, z1 + 0.04, brown)
    box(0.10, y0 - 0.06, z0 - 0.04, 0.12, y0 + 0.015, z1 + 0.04, brown)
    box(0.0, y0, z0 - 0.04, 0.04, y1, z0, brown)
    box(0.0, y0, z1, 0.04, y1, z1 + 0.04, brown)
    box(0.0, y0, zm - 0.005, 0.031, y1, zm + 0.005, (0.7, 0.7, 0.7))
    for z in (z0 + 0.45, z0 + 1.55, zm, z1 - 1.55, z1 - 0.45):
        box(0.0, y0 - 0.14, z - 0.02, 0.05, y0 - 0.06, z + 0.02, dark)
        box(0.0, y0 - 0.14, z - 0.02, 0.10, y0 - 0.11, z + 0.02, dark)
    box(0.0, ytop, 4.70, 0.14, ytop + 0.075, 6.04, kraft)
    box(0.0, ytop, 3.26, 0.14, ytop + 0.075, 4.66, tuple(v * 0.94 for v in kraft))
    box(0.0, ytop + 0.075, 4.70, 0.14, ytop + 0.079, 6.04, (0.82, 0.68, 0.50))
    box(0.0, ytop, 6.62, 0.06, ytop + 0.045, 6.95, (0.55, 0.40, 0.25))
    # แจกันดอกไม้
    vz = 6.72
    vcylinder(0.06, y0, vz, 0.028, 0.10, (0.82, 0.88, 0.93))
    vcylinder(0.06, y0 + 0.07, vz, 0.024, 0.02, (0.55, 0.70, 0.82))
    green = (0.20, 0.50, 0.22)
    tube((0.06, y0 + 0.10, vz), (0.075, y0 + 0.27, vz - 0.03), 0.003, green, 6)
    tube((0.06, y0 + 0.10, vz), (0.045, y0 + 0.24, vz + 0.035), 0.003, green, 6)
    ball(0.075, y0 + 0.28, vz - 0.03, 0.03, (0.88, 0.28, 0.38), 10, 6)
    ball(0.045, y0 + 0.25, vz + 0.035, 0.026, (0.95, 0.85, 0.88), 10, 6)
    # ของบนรางวางปากกา + รอยเขียน
    box(0.04, y0, 6.18, 0.07, y0 + 0.02, 6.26, (0.15, 0.15, 0.16))
    box(0.045, y0, 3.28, 0.07, y0 + 0.022, 3.50, (0.06, 0.06, 0.07))
    box(0.045, y0 + 0.022, 3.28, 0.07, y0 + 0.026, 3.34, (0.70, 0.72, 0.75))
    gquad([(0.003, 1.45, 7.25), (0.003, 1.45, 7.31), (0.003, 1.52, 7.31), (0.003, 1.52, 7.25)], [(0.95, 0.55, 0.15)] * 4)
    sm = (0.80, 0.82, 0.85)
    for (za, zb, ya, yb) in ((3.05, 3.55, 1.55, 1.58), (3.15, 3.45, 1.50, 1.52),
                             (3.70, 3.95, 1.62, 1.65), (3.25, 3.60, 1.40, 1.42)):
        gquad([(0.0315, ya, za), (0.0315, ya, zb), (0.0315, yb, zb), (0.0315, yb, za)], [sm] * 4)
