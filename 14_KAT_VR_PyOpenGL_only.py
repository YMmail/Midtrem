def _oct_r(a, R):  # ประกาศสูตร "ระยะจากกลางถึงขอบแปดเหลี่ยม" ในทิศมุม a (เรเดียน)
    """ระยะจากกึ่งกลางถึงขอบแปดเหลี่ยม ที่มุม a (เรเดียน)"""  # คำอธิบาย: วัดว่าเดินจากกลางไปในทิศมุม a จะถึงขอบแปดเหลี่ยมที่ระยะเท่าไร
    ap = R * math.cos(math.radians(22.5))  # ระยะจากกลางไปตั้งฉากกับกลางด้านแบน (ระยะสั้นสุดไปถึงขอบ)
    d = (a + math.radians(22.5)) % math.radians(45) - math.radians(22.5)  # หาว่าทิศนี้เบี่ยงจากแนวตั้งฉากกับด้านที่ใกล้ที่สุดกี่องศา (อยู่ในช่วง -22.5° ถึง 22.5°)
    return ap / math.cos(d)  # ยิ่งเบี่ยงจากแนวตั้งฉากมาก ระยะยิ่งยาวขึ้น (ไปสุดที่มุมของแปดเหลี่ยม)


def _poly_prism(pts, y0, y1, col, grow=0.0, top=True):  # ประกาศสูตร "สร้างแท่งปริซึม" pts = มุมของฐาน, y0 = ความสูงล่าง, y1 = ความสูงบน, col = สี, grow = ขยายออกด้านข้าง, top = จะปิดฝาด้านบนไหม
    """แท่งปริซึมจากรูปหลายเหลี่ยมนูน (x, z)  grow = ขยายผนังข้างออกไปอีกเล็กน้อย (ใช้ทำแถบสีที่ยื่นออกมา)"""  # คำอธิบาย: แท่งจากฐานหลายเหลี่ยม ค่า grow ใช้ขยายผนังออกเล็กน้อย เอาไว้ทำแถบสีที่นูนออกมา
    n = len(pts)  # นับจำนวนมุมของฐาน
    mx = sum(p[0] for p in pts) / n  # หาจุดกึ่งกลางของฐาน (ค่าเฉลี่ยตำแหน่ง x ของทุกมุม)
    mz = sum(p[1] for p in pts) / n  # ค่าเฉลี่ยตำแหน่ง z ของทุกมุม (รวมกับบรรทัดบนได้จุดกึ่งกลาง)
    glBegin(GL_QUADS)  # เริ่มวาดแผ่นสี่เหลี่ยม สำหรับผนังข้างแต่ละด้าน
    for i in range(n):  # วนทีละด้านของฐาน
        a, b = pts[i], pts[(i + 1) % n]  # จุดสองจุดที่เป็นหัวและท้ายของด้านนี้ (ด้านสุดท้ายวนกลับไปต่อกับจุดแรก)
        ex, ez = b[0] - a[0], b[1] - a[1]  # ทิศทางของด้านนี้ (ลูกศรจากจุด a ไป b)
        L = math.hypot(ex, ez) or 1.0  # ความยาวของด้านนี้ (ถ้าได้ 0 ใช้ 1 กันหารด้วยศูนย์)
        nx, nz = ez / L, -ex / L  # คำนวณทิศที่ "ชี้ตั้งฉากออกจากผนัง" (เรียกว่า เวกเตอร์ตั้งฉาก) ให้ยาว 1
        if nx * ((a[0] + b[0]) / 2 - mx) + nz * ((a[1] + b[1]) / 2 - mz) < 0:  # เช็กว่าทิศนั้นชี้ออกนอกรูปหรือชี้เข้าข้างใน (เทียบกับจุดกึ่งกลาง)
            nx, nz = -nx, -nz  # ถ้าชี้เข้าข้างใน ให้กลับทิศให้ชี้ออกนอก
        sh = 0.55 + 0.45 * max(0.0, nx * LIGHT_N[0] + nz * LIGHT_N[2])  # คำนวณความสว่างของผนังด้านนี้ตามว่าหันเข้าหาแสงแค่ไหน (0.55 มืดสุด ถึง 1.0 สว่างสุด)
        glColor3f(col[0] * sh, col[1] * sh, col[2] * sh)  # ตั้งสีผนังโดยคูณกับความสว่าง
        glVertex3f(a[0] + nx * grow, y0, a[1] + nz * grow)  # มุมล่างของผนังฝั่งจุด a (ขยับออกด้านข้างตามค่า grow)
        glVertex3f(b[0] + nx * grow, y0, b[1] + nz * grow)  # มุมล่างของผนังฝั่งจุด b
        glVertex3f(b[0] + nx * grow, y1, b[1] + nz * grow)  # มุมบนของผนังฝั่งจุด b
        glVertex3f(a[0] + nx * grow, y1, a[1] + nz * grow)  # มุมบนของผนังฝั่งจุด a
    glEnd()  # จบการวาดผนังข้างทั้งหมด
    if top:  # ถ้าต้องการปิดฝาด้านบน
        glColor3f(col[0] * SHADE_TOP, col[1] * SHADE_TOP, col[2] * SHADE_TOP)  # ตั้งสีฝาบนด้วยความสว่างของผิวด้านบน
        glBegin(GL_POLYGON)  # เริ่มวาดรูปหลายเหลี่ยม 1 แผ่น
        for p in pts:  # ไล่ทุกมุมของฐาน
            glVertex3f(p[0], y1, p[1])  # ปักมุมที่ความสูงบนสุด
        glEnd()  # จบการวาดฝาบน


def _arc_band(cx, cz, r0, r1, a0, a1, y0, y1, col, seg=14):  # ประกาศสูตร "แผ่นโค้งเป็นแถบ" (เหมือนส่วนของวงแหวนที่มีความหนาและความสูง) กลาง (cx, cz) รัศมีใน r0 รัศมีนอก r1 มุมเริ่ม a0 มุมจบ a1 สูงจาก y0 ถึง y1
    """แผ่นโค้งตามส่วนของวงกลม (ใช้ทำเบาะพนักหลังของสายรัดเอว)  มุมเป็นองศา x=cos z=sin"""  # คำอธิบาย: แถบโค้งตามส่วนของวงกลม ใช้ทำเบาะพนักหลังของสายรัดเอว มุมเป็นองศา
    a0, a1 = math.radians(a0), math.radians(a1)  # แปลงมุมจากองศาเป็นเรเดียนเพื่อใช้คำนวณ
 
    def sh(nx, nz):  # สูตรย่อย: คำนวณความสว่างจากทิศที่ผิวหันไป
        return 0.55 + 0.45 * max(0.0, nx * LIGHT_N[0] + nz * LIGHT_N[2])  # สว่างระหว่าง 0.55 ถึง 1.0 ตามว่าหันเข้าหาแสงแค่ไหน
 
    def P(r, a, y):  # สูตรย่อย: หาตำแหน่งจริงของจุดที่รัศมี r มุม a ความสูง y
        return (cx + r * math.cos(a), y, cz + r * math.sin(a))  # ส่งคืนตำแหน่ง (x, y, z) บนวงกลม
 
    glBegin(GL_QUADS)  # เริ่มวาดแผ่นสี่เหลี่ยม
    for i in range(seg):  # วนแบ่งแถบโค้งเป็นช่องเล็กๆ ทีละช่อง (ยิ่งแบ่งมากยิ่งโค้งเนียน)
        t0 = a0 + (a1 - a0) * i / seg  # มุมเริ่มของช่องนี้
        t1 = a0 + (a1 - a0) * (i + 1) / seg  # มุมจบของช่องนี้
        tm = (t0 + t1) / 2  # มุมกลางของช่องนี้ (ใช้คำนวณทิศที่ผิวหัน)
        for (r, sg) in ((r1, 1.0), (r0, -1.0)):                       # วาดผนังสองด้านของแถบ: ด้านนอก (หันออกจากศูนย์กลาง) และด้านใน (หันเข้าหาศูนย์กลาง)
            s = sh(sg * math.cos(tm), sg * math.sin(tm))  # คำนวณความสว่างผนังด้านนี้
            glColor3f(col[0] * s, col[1] * s, col[2] * s)  # ตั้งสีโดยคูณกับความสว่าง
            glVertex3f(*P(r, t0, y0)); glVertex3f(*P(r, t1, y0)); glVertex3f(*P(r, t1, y1)); glVertex3f(*P(r, t0, y1))  # ปักมุมทั้ง 4 ของผนังช่องนี้ (ล่างซ้าย ล่างขวา บนขวา บนซ้าย)
        glColor3f(col[0] * SHADE_TOP, col[1] * SHADE_TOP, col[2] * SHADE_TOP)    # ตั้งสีของขอบด้านบนแถบ
        glVertex3f(*P(r0, t0, y1)); glVertex3f(*P(r1, t0, y1)); glVertex3f(*P(r1, t1, y1)); glVertex3f(*P(r0, t1, y1))  # ปักมุมของแผ่นปิดด้านบนช่องนี้
        glColor3f(col[0] * SHADE_BOT, col[1] * SHADE_BOT, col[2] * SHADE_BOT)    # ตั้งสีของขอบด้านล่างแถบ (มืดกว่าเพราะอยู่ใต้)
        glVertex3f(*P(r0, t0, y0)); glVertex3f(*P(r1, t0, y0)); glVertex3f(*P(r1, t1, y0)); glVertex3f(*P(r0, t1, y0))  # ปักมุมของแผ่นปิดด้านล่างช่องนี้
    for a in (a0, a1):                                                          # ปิดหัวและท้ายของแถบโค้ง ด้วยแผ่นตั้งสองแผ่น
        glColor3f(col[0] * 0.8, col[1] * 0.8, col[2] * 0.8)  # ตั้งสีเข้มลงนิดหน่อย (80%)
        glVertex3f(*P(r0, a, y0)); glVertex3f(*P(r1, a, y0)); glVertex3f(*P(r1, a, y1)); glVertex3f(*P(r0, a, y1))  # ปักมุมทั้ง 4 ของแผ่นปิดปลายแถบ
    glEnd()  # จบการวาดแถบทั้งหมด


def kat_vr(logo, cx, cz, yaw):  # ประกาศสูตร "สร้างเครื่อง KAT VR ทั้งตัว" logo = ภาพโลโก้, (cx, cz) = ตำแหน่ง, yaw = องศาหมุนรอบตัว
    """KAT VR  ลู่เดิน VR 360° ตามรูป: ฐานแปดเหลี่ยมสีดำมีแถบฟ้า แผ่นเดินเว้าลายซี่ มีวงขาว
    บันไดพรมยื่นออกด้านหน้า (เลข 6)  ขา 3 ขาชี้ขึ้นไปห่วงรัดเอว + เบาะพนักหลัง + สายรัดห้อย
    กล่องเซนเซอร์สูงด้านบนมีลายฟ้า (เลข 4)  ก่อนหมุน บันไดชี้ไปทาง +Z  yaw = หมุนรอบแกนตั้ง (องศา)"""  # คำอธิบายองค์ประกอบทั้งหมดของเครื่อง: ฐาน แผ่นเดิน บันได ขา ห่วงรัดเอว เบาะ สาย กล่องเซนเซอร์ (ก่อนหมุน บันไดหันไปทางประตู)
    blk, cyan, white = KAT_BLACK, KAT_CYAN, (0.92, 0.92, 0.94)  # ตั้งชื่อสีย่อ: ดำ ฟ้า ขาว
    pad = (0.12, 0.12, 0.13)  # สีเทาเข้มของเบาะรัดเอว
    R, Hb, pr = KAT_R, KAT_H, KAT_PAD_R  # ตั้งชื่อย่อให้ค่าคงที่: รัศมีฐาน (R) ความสูงฐาน (Hb) รัศมีแผ่นเดิน (pr)
    glPushMatrix()  # "จำตำแหน่งเดิมไว้" ก่อนจะขยับ/หมุนจุดวาด (เหมือนบันทึกเกม)
    glTranslatef(cx, 0, cz)  # ย้ายจุดวาดไปยืนที่ตำแหน่งของเครื่องบนพื้น จากนี้ทุกอย่างวาดสัมพันธ์กับจุดนี้
    glRotatef(yaw, 0, 1, 0)  # หมุนจุดวาดรอบแกนตั้งตามองศา yaw ทำให้เครื่องทั้งตัวหันไปทิศที่ต้องการ
 
    # ---------- ฐาน ----------
    _poly_prism(_oct_pts(R), 0.0, Hb, blk, top=False)  # สร้างฐานเป็นแท่งแปดเหลี่ยมสีดำ สูงตามค่า Hb (ยังไม่ปิดฝาบน เพราะเดี๋ยวจะวาดแผ่นเดินและขอบแยกต่างหาก)
    _poly_prism(_oct_pts(R), 0.075, 0.115, cyan, grow=0.003, top=False)          # สร้างแถบสีฟ้ารอบฐาน เป็นแท่งแปดเหลี่ยมบางๆ (สูง 7.5-11.5 ซม.) ที่นูนออกมา 3 มม.
    seg = 64  # จำนวนช่องที่แบ่งวงกลม (ยิ่งมากยิ่งกลมเนียน)
    rin = pr + 0.025  # รัศมีขอบในของหน้าบนฐาน = รัศมีแผ่นเดิน + 2.5 ซม. (เว้นที่ไว้ให้วงขาว)
    glColor3f(0.08, 0.08, 0.09)                                                  # ตั้งสีดำเข้มของหน้าบนฐาน (ส่วนวงแหวนระหว่างแผ่นเดินกับขอบนอกแปดเหลี่ยม)
    glBegin(GL_QUADS)  # เริ่มวาดแผ่นสี่เหลี่ยม
    for i in range(seg):  # วนทีละช่องรอบวง
        a0, a1 = 2 * math.pi * i / seg, 2 * math.pi * (i + 1) / seg  # มุมเริ่มและมุมจบของช่องนี้
        glVertex3f(rin * math.cos(a0), Hb, rin * math.sin(a0))  # มุมที่ 1: ขอบในด้านมุมเริ่ม
        glVertex3f(_oct_r(a0, R) * math.cos(a0), Hb, _oct_r(a0, R) * math.sin(a0))  # มุมที่ 2: ขอบนอก (ตามรูปแปดเหลี่ยม) ด้านมุมเริ่ม
        glVertex3f(_oct_r(a1, R) * math.cos(a1), Hb, _oct_r(a1, R) * math.sin(a1))  # มุมที่ 3: ขอบนอกด้านมุมจบ
        glVertex3f(rin * math.cos(a1), Hb, rin * math.sin(a1))  # มุมที่ 4: ขอบในด้านมุมจบ
    glEnd()  # จบการวาดหน้าบนฐาน
    glColor3f(*white)                                                            # ตั้งสีขาวสำหรับวงขาวรอบแผ่นเดิน
    glBegin(GL_QUADS)  # เริ่มวาดแผ่นสี่เหลี่ยม
    for i in range(seg):  # วนทีละช่องรอบวง
        a0, a1 = 2 * math.pi * i / seg, 2 * math.pi * (i + 1) / seg  # มุมเริ่มและมุมจบของช่องนี้
        for (r, a) in ((pr, a0), (rin, a0), (rin, a1), (pr, a1)):  # ไล่ 4 มุมของแผ่นช่องนี้ (รัศมีในและรัศมีนอก ทั้งสองมุม)
            glVertex3f(r * math.cos(a), Hb + 0.002, r * math.sin(a))  # ปักมุมที่ลอยเหนือหน้าบนฐานเล็กน้อย (2 มม.) ไม่ให้ภาพทับกันจนกระพริบ
    glEnd()  # จบการวาดวงขาว
 
    # ---------- แผ่นเดินเว้าเป็นจาน + ซี่ร่องกระจายจากกลาง ----------
    y_mid = Hb - 0.055  # ความสูงตรงกลางแผ่นเดิน ต่ำกว่าขอบ 5.5 ซม. (ทำให้เว้าเป็นจาน)
 
    def dish_y(r):  # สูตรย่อย: ความสูงของแผ่นเดินที่ระยะ r จากกลาง
        return y_mid + (Hb - y_mid) * (r / pr) ** 2  # กลางต่ำสุด ยิ่งออกไปขอบยิ่งสูงขึ้นแบบโค้ง (ตามสูตรพาราโบลา) จนถึงระดับขอบที่ Hb
 
    rings, sg = 7, 48  # แบ่งแผ่นเดินเป็น 7 วงจากกลางออกขอบ และ 48 ช่องรอบวง
    glBegin(GL_QUADS)  # เริ่มวาดแผ่นสี่เหลี่ยม
    for k in range(rings):  # วนทีละวงจากกลางออกขอบ
        r0, r1 = pr * k / rings, pr * (k + 1) / rings  # รัศมีขอบในและขอบนอกของวงนี้
        for i in range(sg):  # วนทีละช่องรอบวง
            a0, a1 = 2 * math.pi * i / sg, 2 * math.pi * (i + 1) / sg  # มุมเริ่มและมุมจบของช่องนี้
            s = (1.0 if i % 2 == 0 else 0.88) * (0.80 + 0.20 * (k + 1) / rings)  # ความสว่าง: ช่องเลขคี่มืดลง 12% ทำให้เป็นลายซี่สลับสี และยิ่งออกขอบยิ่งสว่างขึ้น
            glColor3f(0.085 * s, 0.085 * s, 0.095 * s)  # ตั้งสีดำอมเทา คูณกับความสว่าง
            for (r, a) in ((r0, a0), (r1, a0), (r1, a1), (r0, a1)):  # ไล่ 4 มุมของแผ่นช่องนี้
                glVertex3f(r * math.cos(a), dish_y(r), r * math.sin(a))  # ปักมุมที่ระดับความสูงตามความเว้าของจาน
    glEnd()  # จบการวาดแผ่นเดิน
    glColor3f(0.20, 0.20, 0.22)  # ตั้งสีเทาสำหรับเส้นร่องที่พุ่งออกจากกลาง
    glBegin(GL_QUADS)  # เริ่มวาดแผ่นสี่เหลี่ยม
    for j in range(36):  # วนทำร่อง 36 เส้น กระจายรอบวงทุก 10 องศา
        a = 2 * math.pi * j / 36  # มุมของร่องเส้นนี้
        for (r, da) in ((0.10, -0.012), (0.10, 0.012), (pr - 0.04, 0.003), (pr - 0.04, -0.003)):  # ไล่ 4 มุมของร่อง ซึ่งเป็นแถบเรียวแหลมที่กว้างตรงกลาง (r=0.10) และแคบตรงขอบ
            glVertex3f(r * math.cos(a + da), dish_y(r) + 0.0012, r * math.sin(a + da))  # ปักมุมที่ลอยเหนือพื้นแผ่นเดิน 1.2 มม. ไม่ให้ภาพทับกันจนกระพริบ
