    k = (1, 1, 1, 1, 1, 1) if flat else (SHADE_TOP, SHADE_BOT, SHADE_N, SHADE_S, SHADE_W, SHADE_E)  # เลือกค่าความสว่างของแต่ละด้าน (ถ้า flat ทุกด้านเท่ากัน)
